const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const source = fs.readFileSync(
  path.join(__dirname, '../sources/apple-music/index.js'), 'utf8'
);
const manifest = JSON.parse(fs.readFileSync(
  path.join(__dirname, '../sources/apple-music/manifest.json'), 'utf8'
));
const playlistId = 'pl.u-vxy69qDuPlg7km';
const reportedUrl = `https://music.apple.com/us/playlist/atmos/${playlistId}`;

function runtime() {
  let registered;
  const context = vm.createContext({
    registerExtension(value) { registered = value; },
    log: { info() {}, warn() {}, error() {}, debug() {} },
    storage: { get() {}, set() {} },
  });
  vm.runInContext(source, context);
  return { context, registered };
}

for (const [url, type, id, storefront] of [
  [reportedUrl, 'playlist', playlistId, 'us'],
  [`${reportedUrl}?l=en-US&ls=1#tracks`, 'playlist', playlistId, 'us'],
  [`${reportedUrl}/`, 'playlist', playlistId, 'us'],
  [`https://music.apple.com/gb/playlist/${playlistId}`, 'playlist', playlistId, 'gb'],
  ['https://music.apple.com/us/playlist/hits/pl.abcdef123456', 'playlist', 'pl.abcdef123456', 'us'],
  ['https://music.apple.com/us/album/example/12345?i=67890&ls=1', 'track', '67890', 'us'],
  ['https://music.apple.com/us/album/12345?i=67890#lyrics', 'track', '67890', 'us'],
  ['https://music.apple.com/us/album/example/12345#?i=67890', 'album', '12345', 'us'],
  ['https://music.apple.com/us/album/example/12345?i=67890invalid', 'album', '12345', 'us'],
  ['https://music.apple.com/jp/song/%E6%AD%8C/12345', 'track', '12345', 'jp'],
  ['  https://music.apple.com/GB/artist/example/12345  ', 'artist', '12345', 'gb'],
  ['music.apple.com/us/song/example/12345', 'track', '12345', 'us'],
]) {
  test(`parses complete Apple Music URL: ${url}`, () => {
    const { context } = runtime();
    assert.deepEqual(JSON.parse(JSON.stringify(context.parseAppleMusicURL(url))), {
      type, id, storefront,
    });
  });
}

for (const [type, template] of Object.entries(manifest.capabilities.shareUrlTemplates)) {
  test(`accepts the ${type} share URL generated by the manifest`, () => {
    const { context } = runtime();
    const id = type === 'playlist' ? playlistId : '12345';
    const parsed = context.parseAppleMusicURL(template.replace('{id}', id));
    assert.equal(parsed.id, id);
    assert.equal(parsed.type, type);
  });
}

for (const url of [
  '',
  'https://music.apple.com/us/playlist/',
  `https://example.test/music.apple.com/us/playlist/atmos/${playlistId}`,
  `https://music.apple.com.example.test/us/playlist/atmos/${playlistId}`,
  `https://music.apple.com@elsewhere.test/us/playlist/atmos/${playlistId}`,
  `${reportedUrl}/extra`,
  `${reportedUrl}%2Fextra`,
  `https://music.apple.com/us/playlist/name/extra/${playlistId}`,
]) {
  test(`rejects incomplete or unrelated URL: ${url}`, () => {
    const { context } = runtime();
    assert.equal(context.parseAppleMusicURL(url), null);
  });
}

test('reported playlist reaches the catalog with its full ID and loads subsequent pages', () => {
  const { context, registered } = runtime();
  registered.initialize({ storefront: 'jp' });
  const requests = [];
  const song = id => ({
    id, type: 'songs', attributes: { name: `Song ${id}`, artistName: 'Artist' },
  });
  context.apiGet = request => {
    requests.push({ request, storefront: vm.runInContext('state.storefront', context) });
    if (request === `playlists/${playlistId}?include=tracks&extend=editorialArtwork,editorialVideo`) {
      return { data: [{
        id: playlistId,
        attributes: { name: 'Atmos', curatorName: 'Playlist owner' },
        relationships: { tracks: {
          data: [song('1')],
          next: `/v1/catalog/us/playlists/${playlistId}/tracks?offset=1`,
        } },
      }] };
    }
    assert.equal(request, `playlists/${playlistId}/tracks?offset=1`);
    return { data: [song('2')] };
  };
  const result = registered.handleUrl(reportedUrl);
  assert.equal(result.success, true);
  assert.equal(result.type, 'playlist');
  assert.equal(result.id, playlistId);
  assert.equal(result.playlist.total_tracks, 2);
  assert.deepEqual(Array.from(result.tracks, track => track.playlist_position), [1, 2]);
  assert.equal(requests.length, 2);
  assert.ok(requests.every(request => request.storefront === 'us'));
  assert.equal(vm.runInContext('state.storefront', context), 'jp');
});

test('a playlist fetch failure restores the configured storefront', () => {
  const { context, registered } = runtime();
  registered.initialize({ storefront: 'jp' });
  context.apiGet = () => { throw new Error('API request failed: HTTP 404'); };
  const result = registered.handleUrl(reportedUrl);
  assert.equal(result.success, false);
  assert.match(result.error, /HTTP 404/);
  assert.equal(vm.runInContext('state.storefront', context), 'jp');
});
